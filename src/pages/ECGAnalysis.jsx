import { useState } from 'react'
import { analyzeEcg } from '../api'
import EducationalSection from '../components/EducationalSection'
import FileUpload from '../components/FileUpload'
import ResultsPanel from '../components/ResultsPanel'
import SignalChart from '../components/SignalChart'
import { createDemoWaveform } from '../utils/demoWaveform'
import {
  ECG_EXTENSIONS,
  preparePreview,
  validateSignalFile,
} from '../utils/signalFile'

function ECGAnalysis() {
  const [file, setFile] = useState(null)
  const [fileError, setFileError] = useState('')
  const [preview, setPreview] = useState({
    series: null,
    isDemo: false,
    note: '',
  })
  const [result, setResult] = useState({ status: 'idle' })

  async function handleFileChosen(selected) {
    const validation = validateSignalFile(selected, 'ecg')
    if (!validation.ok) {
      setFile(null)
      setFileError(validation.message)
      setPreview({ series: null, isDemo: false, note: '' })
      setResult({ status: 'idle' })
      return
    }

    setFileError('')
    setFile(selected)
    setResult({ status: 'idle' })

    const prepared = await preparePreview(selected)
    if (prepared.canParse) {
      setPreview({
        series: prepared.series,
        isDemo: false,
        note: prepared.note,
      })
      return
    }

    setPreview({
      series: createDemoWaveform('ecg'),
      isDemo: true,
      note: `${prepared.note} The chart below is labeled demonstration data and is not the uploaded recording.`,
    })
  }

  async function handleAnalyze() {
    if (!file) {
      setFileError('Upload a valid ECG file before running analysis.')
      return
    }

    setResult({ status: 'loading' })
    const response = await analyzeEcg(file)
    setResult(response)
  }

  return (
    <div className="space-y-6">
      <div>
        <h1 className="text-2xl font-semibold text-slate-900">ECG analysis</h1>
        <p className="mt-2 max-w-3xl text-sm text-slate-600">
          Upload an ECG recording, preview it when the format can be parsed,
          then request analysis. Results stay on this page. No diagnosis is
          generated by the interface itself.
        </p>
      </div>

      <FileUpload
        accept={ECG_EXTENSIONS.join(',')}
        selectedFile={file}
        error={fileError}
        onFileChosen={handleFileChosen}
      />

      <SignalChart
        title="ECG signal preview"
        series={preview.series}
        isDemo={preview.isDemo}
        note={preview.note}
      />

      <div className="flex flex-col gap-3 sm:flex-row sm:items-center">
        <button
          type="button"
          onClick={handleAnalyze}
          disabled={!file || result.status === 'loading'}
          className="inline-flex items-center justify-center rounded-md bg-clinical-700 px-4 py-2.5 text-sm font-medium text-white hover:bg-clinical-800 disabled:cursor-not-allowed disabled:bg-slate-400"
        >
          {result.status === 'loading' ? 'Analyzing…' : 'Analyze ECG'}
        </button>
        <p className="text-sm text-slate-500">
          Analysis calls the FastAPI service when it is available.
        </p>
      </div>

      <ResultsPanel result={result} />

      <EducationalSection title="What is an ECG? (for patients and learners)">
        <p>
          ECG stands for electrocardiogram. It records the electrical signals
          that make the heart contract. Stick-on electrodes on the chest, arms,
          or legs pick up those signals.
        </p>
        <p>
          The familiar ECG tracing shows repeating waves that relate to each
          heartbeat. A clinician looks at rate, rhythm, and shape, together with
          symptoms and other findings. A single picture of a waveform is not a
          diagnosis.
        </p>
        <p>
          This page may show a preview of simple text files, or a labeled
          demonstration waveform when a clinical format cannot be parsed in the
          browser. Do not use it to confirm a heart condition. Seek care from a
          qualified healthcare professional.
        </p>
      </EducationalSection>
    </div>
  )
}

export default ECGAnalysis
