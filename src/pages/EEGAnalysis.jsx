import { useState } from 'react'
import { analyzeEeg } from '../api'
import EducationalSection from '../components/EducationalSection'
import FileUpload from '../components/FileUpload'
import ResultsPanel from '../components/ResultsPanel'
import SignalChart from '../components/SignalChart'
import { createDemoWaveform } from '../utils/demoWaveform'
import {
  EEG_EXTENSIONS,
  preparePreview,
  validateSignalFile,
} from '../utils/signalFile'

function EEGAnalysis() {
  const [file, setFile] = useState(null)
  const [fileError, setFileError] = useState('')
  const [preview, setPreview] = useState({
    series: null,
    isDemo: false,
    note: '',
  })
  const [result, setResult] = useState({ status: 'idle' })

  async function handleFileChosen(selected) {
    const validation = validateSignalFile(selected, 'eeg')
    if (!validation.ok) {
      setFile(null)
      setFileError(validation.message)
      setPreview({ series: null, isDemo: false, note: '' })
      setResult({ status: 'idle' })
      return
    }

    setFileError('')
    setFile(selected)
    setResult({ status: 'idle' })

    const prepared = await preparePreview(selected)
    if (prepared.canParse) {
      setPreview({
        series: prepared.series,
        isDemo: false,
        note: prepared.note,
      })
      return
    }

    setPreview({
      series: createDemoWaveform('eeg'),
      isDemo: true,
      note: `${prepared.note} The chart below is labeled demonstration data and is not the uploaded recording.`,
    })
  }

  async function handleAnalyze() {
    if (!file) {
      setFileError('Upload a valid EEG file before running analysis.')
      return
    }

    setResult({ status: 'loading' })
    const response = await analyzeEeg(file)
    setResult(response)
  }

  return (
    <div className="space-y-6">
      <div>
        <h1 className="text-2xl font-semibold text-slate-900">EEG analysis</h1>
        <p className="mt-2 max-w-3xl text-sm text-slate-600">
          Upload an EEG recording, preview it when the format can be parsed,
          then request analysis. Results stay on this page. No diagnosis is
          generated by the interface itself.
        </p>
      </div>

      <FileUpload
        accept={EEG_EXTENSIONS.join(',')}
        selectedFile={file}
        error={fileError}
        onFileChosen={handleFileChosen}
      />

      <SignalChart
        title="EEG signal preview"
        series={preview.series}
        isDemo={preview.isDemo}
        note={preview.note}
      />

      <div className="flex flex-col gap-3 sm:flex-row sm:items-center">
        <button
          type="button"
          onClick={handleAnalyze}
          disabled={!file || result.status === 'loading'}
          className="inline-flex items-center justify-center rounded-md bg-clinical-700 px-4 py-2.5 text-sm font-medium text-white hover:bg-clinical-800 disabled:cursor-not-allowed disabled:bg-slate-400"
        >
          {result.status === 'loading' ? 'Analyzing…' : 'Analyze EEG'}
        </button>
        <p className="text-sm text-slate-500">
          Analysis calls the FastAPI service when it is available.
        </p>
      </div>

      <ResultsPanel result={result} />

      <EducationalSection title="What is an EEG? (for patients and learners)">
        <p>
          EEG stands for electroencephalogram. It measures small electrical
          signals produced when brain cells communicate. Sensors are usually
          placed on the scalp with a conductive gel or a cap.
        </p>
        <p>
          A recording looks like several wavy lines, one for each sensor. Those
          lines are not thoughts or a diagnosis. They are voltage changes over
          time. A clinician interprets them together with symptoms, history, and
          other tests.
        </p>
        <p>
          This page can show a simple preview of some file types. It cannot
          confirm epilepsy, sleep disorders, or any other condition. Always
          discuss EEG results with a qualified healthcare professional.
        </p>
      </EducationalSection>
    </div>
  )
}

export default EEGAnalysis
